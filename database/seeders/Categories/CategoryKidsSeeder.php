        foreach ($paths as $path) {
            CategoryPathAction::run($path);
        }

        $kidsRootCategory = Category::query()
            ->where('name', 'Товары для детей')
            ->whereNull('parent_id')
            ->first();

        if (! $kidsRootCategory) {
