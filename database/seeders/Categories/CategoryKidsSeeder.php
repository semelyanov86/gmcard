        $iconDataByCategoryName = [
            'Одежда и обувь' => ['icon_index' => 1, 'icon_name' => 'clothes-and-shoes'],
            'Уход и гигиена' => ['icon_index' => 2, 'icon_name' => 'care-and-hygiene'],
            'Питание' => ['icon_index' => 3, 'icon_name' => 'nutrition'],
