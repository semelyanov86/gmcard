    private function clearSectionChildren(string $rootName, string $sectionName): void
    {
        $root = Category::query()
            ->where('name', $rootName)
            ->whereNull('parent_id')
            ->first();

        if (! $root) {
            return;
        }

        $section = Category::query()
            ->where('parent_id', $root->id)
            ->where('name', $sectionName)
            ->first();

        if (! $section) {
            return;
        }

        $section->descendants()->delete();
    }

    private function removeTopSection(string $rootName, string $sectionName): void
    {
        $root = Category::query()
            ->where('name', $rootName)
            ->whereNull('parent_id')
            ->first();

        if (! $root) {
            return;
        }

        $section = Category::query()
            ->where('parent_id', $root->id)
            ->where('name', $sectionName)
            ->first();

        if (! $section) {
            return;
        }

        $section->delete();
    }
